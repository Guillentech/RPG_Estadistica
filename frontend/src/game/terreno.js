// ============================================================================
// 🗺️ TERRENOS 16×16 · 30 columnas × 17 filas
// Leyenda:
// '~' = Agua      '^' = Acantilado      '.' = Pasto
// ',' = Flores    '#' = Árbol           ':' = Pasto arcano
// '*' = Cristal   'T' = Pino arcano      '=' = Camino      'B' = Puente
// ============================================================================
export const TILE_SIZE = 16;
export const COLS_MAPA = 30;
export const FILAS_MAPA = 17;
export const ANCHO_LOGICO = COLS_MAPA * TILE_SIZE; // 480 px
export const ALTO_LOGICO = FILAS_MAPA * TILE_SIZE; // 272 px

const agua = '~'.repeat(COLS_MAPA);
const bordeRocoso = `~${'^'.repeat(28)}~`;

// Construye un mapa con borde de agua/roca y 13 filas interiores de 26 tiles.
const crearMapa = (filasInteriores, base = '.') => [
  agua,
  bordeRocoso,
  ...filasInteriores.map(fila => `~^${fila.padEnd(26, base).slice(0, 26)}^~`),
  bordeRocoso,
  agua
];

